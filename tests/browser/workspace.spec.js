import { test, expect } from '@playwright/test'

test('admin and member can complete the workspace flow without browser-managed credentials', async ({ page, context }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/#/login')
  await expect(page.getByRole('heading', { name: '登录工作台' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('login-desktop.png'), fullPage: true })
  await page.getByLabel('账号', { exact: true }).fill('test-admin')
  await page.getByLabel('密码', { exact: true }).fill('Browser-test-password-47!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '货号搭配工作台' })).toBeVisible()
  const cookies = await context.cookies()
  expect(cookies.find((cookie) => cookie.name === 'saltum_session')?.httpOnly).toBe(true)
  expect(await page.evaluate(() => document.cookie.includes('saltum_session'))).toBe(false)

  await page.getByRole('link', { name: '商品目录', exact: true }).click()
  await page.getByRole('button', { name: '新建商品', exact: true }).click()
  await page.getByLabel('商品货号', { exact: true }).fill('J566')
  await page.getByLabel('商品名称', { exact: true }).fill('SALTUM 网球裙')
  await page.getByLabel('品类', { exact: true }).fill('裙装')
  await page.getByLabel('配色', { exact: true }).fill('奶白，深绿')
  await page.getByRole('button', { name: '保存商品', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'SALTUM 网球裙', exact: true })).toBeVisible()

  await page.getByRole('link', { name: '搭配工作台', exact: true }).click()
  await page.getByRole('button', { name: '新建搭配', exact: true }).click()
  const editor = page.locator('form.editor')
  await editor.getByLabel('搭配名称').fill('Tennis to Café')
  await editor.getByLabel('主款货号').selectOption('J566')
  await editor.getByLabel('主款颜色').selectOption('奶白')
  await editor.getByLabel('搭配说明').fill('从网球场走进日常，保留简洁的奶白色搭配。')
  await editor.getByRole('button', { name: '保存搭配' }).click()
  await expect(page.getByRole('heading', { name: 'Tennis to Café', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Tennis to Café', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('workbench-desktop.png'), fullPage: true })

  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('workbench-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1000 })

  await page.getByRole('link', { name: '图片任务', exact: true }).click()
  await page.getByLabel('商品货号', { exact: true }).fill('J566')
  await page.getByLabel('商品名称', { exact: true }).fill('三视图需求')
  await page.getByRole('button', { name: '保存任务草稿' }).click()
  await expect(page.getByRole('heading', { name: '三视图需求', exact: true })).toBeVisible()
  await expect(page.locator('.task-card').getByText('草稿', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: '成员管理', exact: true }).click()
  await page.getByLabel('成员账号').fill('alice')
  await page.getByLabel('成员姓名').fill('成员 Alice')
  await page.getByLabel('初始密码').fill('Member-browser-password-29!')
  await page.getByRole('button', { name: '创建成员账号' }).click()
  await expect(page.getByRole('cell', { name: '成员 Alice', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录工作台' })).toBeVisible()

  await page.getByLabel('账号', { exact: true }).fill('alice')
  await page.getByLabel('密码', { exact: true }).fill('Member-browser-password-29!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '货号搭配工作台' })).toBeVisible()
  await expect(page.getByRole('link', { name: '成员管理', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Tennis to Café' })).toBeVisible()
  expect((await context.request.get('/api/v1/members')).status()).toBe(403)
  await page.getByRole('link', { name: '商品目录', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建商品', exact: true })).toHaveCount(0)
  await expect(page.getByRole('cell', { name: 'J566', exact: true })).toBeVisible()
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  expect(errors).toEqual([])
})
